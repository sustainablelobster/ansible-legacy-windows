import argparse
import hashlib
from pathlib import Path

SOURCE_URL = "https://www.unicode.org/Public/8.0.0/ucd/UnicodeData.txt"
SOURCE_SHA256 = "38b17e1118206489a7e0ab5d29d7932212d38838df7d3ec025ecb58e8798ec20"
NAMES = (
    "Lu",
    "Ll",
    "Lt",
    "Lm",
    "Lo",
    "Mn",
    "Mc",
    "Me",
    # The decimal-number code is the official Unicode identifier.
    "Nd",  # codespell:ignore nd
    "Nl",
    "No",
    "Zs",
    "Zl",
    "Zp",
    "Cc",
    "Cf",
    "Cs",
    "Co",
    "Pc",
    "Pd",
    "Ps",
    "Pe",
    "Pi",
    "Pf",
    "Po",
    "Sm",
    "Sc",
    "Sk",
    "So",
    "Cn",
)


def _bmp_categories(source: bytes) -> list[str]:
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError("The input is not the recorded Unicode8 source file.")
    values = ["Cn"] * 65536
    pending_start = -1
    pending_category = ""
    for line in source.decode("utf-8").splitlines():
        code, name, category = line.split(";")[:3]
        number = int(code, 16)
        if number > 65535:
            break
        if category not in NAMES:
            raise ValueError("Unknown Unicode category: " + category)
        if name.endswith(", First>"):
            pending_start, pending_category = number, category
        elif name.endswith(", Last>"):
            if pending_start < 0 or pending_category != category:
                raise ValueError("Unpaired Unicode category range.")
            values[pending_start : number + 1] = [category] * (
                number + 1 - pending_start
            )
            pending_start, pending_category = -1, ""
        else:
            values[number] = category
    if pending_start >= 0:
        raise ValueError("Unterminated Unicode category range.")
    return values


def render(source: bytes) -> str:
    """Render fixed BMP ranges without using the development Unicode database.

    :param source: Literal official Unicode8 UnicodeData.txt bytes.
    :returns: Target-compatible Python containing only readable category facts.
    :raises ValueError: Source identity or paired First/Last records differ.
    """
    values = _bmp_categories(source)
    groups: dict[str, list[tuple[int, int]]] = {name: [] for name in NAMES}
    start = 0
    for end in range(1, 65537):
        if end == 65536 or values[end] != values[start]:
            groups[values[start]].append((start, end - 1))
            start = end
    output = [
        "# -*- coding: utf-8 -*-",
        "# Copyright (c) 1991-2015 Unicode, Inc.",
        "# SPDX-License-Identifier: Unicode-3.0",
        "",
        '"""Unicode8 general-category ranges for individual UTF-16 code units.',
        "",
        "Derived from " + SOURCE_URL,
        "Source SHA256: " + SOURCE_SHA256,
        "Regenerate/check using scripts/generate_regex_categories.py; no host",
        "Unicode database or Windows/managed runtime supplies these fixed facts.",
        '"""',
        "",
        "# Generated facts stay one inclusive range per line for reviewable diffs.",
        "# This data-only file has no control flow to split into smaller modules.",
        "# pylint: disable=too-many-lines",
        'UNICODE_VERSION = "8.0.0"',
        "CATEGORY_RANGES = {",
    ]
    for name, ranges in groups.items():
        if len(ranges) == 1:
            first, last = ranges[0]
            output.append(f'    "{name}": ((0x{first:04X}, 0x{last:04X}),),')
            continue
        if name == "Nd":  # codespell:ignore nd
            output.append(
                "    # The decimal-number code is the official Unicode identifier."
            )
            output.append('    "' + name + '": (  # codespell:ignore nd')
        else:
            output.append('    "' + name + '": (')
        output.extend(
            f"        (0x{first:04X}, 0x{last:04X})," for first, last in ranges
        )
        output.append("    ),")
    output.extend(["}", ""])
    return "\n".join(output)


def main() -> None:
    """Generate or verify the dataset locally from an explicit offline input.

    :raises ValueError: Source identity, category ranges or generated bytes differ.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    expected = render(arguments.source.read_bytes()).encode("utf-8")
    if arguments.check:
        if arguments.output.read_bytes() != expected:
            raise ValueError("The shipped category facts differ from the source.")
        print("PASS: complete readable Unicode8 BMP category facts reproduce literally")
    else:
        arguments.output.write_bytes(expected)


if __name__ == "__main__":
    main()
