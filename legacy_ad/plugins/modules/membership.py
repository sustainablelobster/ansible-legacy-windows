_PARAMETERS = (
    "dns_domain_name",
    "domain_admin_user",
    "domain_admin_password",
    "domain_ou_path",
    "domain_server",
    "hostname",
    "offline_join_blob",
    "reboot",
    "reboot_timeout",
    "state",
    "workgroup_name",
)


def _parameters(arguments):
    values = {
        name: as_string(arguments.get(name), name)
        for name in _PARAMETERS
        if name not in ("reboot", "reboot_timeout")
    }
    for name, value in values.items():
        if value is not None and "\0" in value:
            raise ValueError(name + " must not contain NUL characters.")
    values["reboot"] = as_bool(arguments.get("reboot", False), "reboot")
    values["reboot_timeout"] = as_int32(
        arguments.get("reboot_timeout", 600), "reboot_timeout"
    )
    if values["state"] is not None:
        values["state"] = values["state"].lower()
    if values["state"] not in ("domain", "workgroup"):
        raise ValueError("state is required and must be domain or workgroup.")
    if values["offline_join_blob"] is not None:
        for name in (
            "domain_admin_user",
            "dns_domain_name",
            "domain_ou_path",
            "hostname",
        ):
            if values[name] is not None:
                raise ValueError(
                    "offline_join_blob is mutually exclusive with " + name + "."
                )
    user = values["domain_admin_user"]
    password = values["domain_admin_password"]
    if (user is None) != (password is None):
        raise ValueError(
            "domain_admin_user and domain_admin_password must be provided together."
        )
    if (
        values["state"] == "domain"
        and user is None
        and values["offline_join_blob"] is None
    ):
        raise ValueError(
            "state=domain requires domain_admin_user or offline_join_blob."
        )
    if values["state"] == "workgroup":
        required = ("workgroup_name", "domain_admin_user", "domain_admin_password")
        missing = [name for name in required if values[name] is None]
        if missing:
            raise ValueError("state=workgroup requires " + ", ".join(missing) + ".")
    return values


def _different(left, right):
    return (
        left.lower() != right.lower()
        if left is not None and right is not None
        else left != right
    )


def _online_join(parameters, requested_name, result, check_mode):
    domain = parameters["dns_domain_name"]
    if not domain:
        raise ValueError("dns_domain_name must not be empty for an online domain join.")
    if not check_mode:
        try:
            native.join_domain(
                domain,
                parameters["domain_admin_user"],
                parameters["domain_admin_password"],
                parameters["domain_ou_path"],
                parameters["domain_server"],
                requested_name,
            )
        except OSError as error:
            if getattr(error, "rename_applied", False) or getattr(
                error, "join_applied", False
            ):
                result.update(changed=True, reboot_required=True)
            if error.errno == 2:
                raise OSError(
                    str(error) + " Check domain_ou_path is pointing to a valid OU "
                    "in the target domain."
                ) from None
            raise
    result.update(changed=True, reboot_required=True)


def _offline_join(text, check_mode):
    native.require_offline_join()
    if not check_mode:
        try:
            # Windows FromBase64String ignores these four whitespace characters.
            compact = text.translate(str.maketrans("", "", " \t\r\n"))
            blob = base64.b64decode(compact.encode("ascii"), validate=True)
        except (ValueError, UnicodeError, binascii.Error):
            raise ValueError(
                "offline_join_blob must be valid base64 provisioning data."
            ) from None
        native.join_offline(blob)


def _workgroup_join(parameters, current, result, check_mode):
    name = parameters["workgroup_name"]
    if not name:
        raise ValueError("workgroup_name must not be empty.")
    if not check_mode:
        try:
            native.join_workgroup(
                name,
                parameters["domain_admin_user"],
                parameters["domain_admin_password"],
                current["state"] == "domain",
            )
        except OSError as error:
            if getattr(error, "unjoin_applied", False):
                result.update(changed=True, reboot_required=True)
            raise
    result.update(changed=True, reboot_required=True)


def _manage(parameters, check_mode=False, diff_mode=False):
    current = native.current_state()
    result = {"changed": False, "reboot_required": False}
    requested_name = parameters["hostname"] or current["hostname"]
    rename = _different(requested_name, current["hostname"])
    domain = parameters["dns_domain_name"]
    workgroup = parameters["workgroup_name"]
    user = parameters["domain_admin_user"]
    password = parameters["domain_admin_password"]
    state = parameters["state"]
    if diff_mode:
        result["diff"] = {"before": current.copy(), "after": {}}
    try:
        if state == "domain" and parameters["offline_join_blob"]:
            if current["state"] != "domain":
                _offline_join(parameters["offline_join_blob"], check_mode)
                result.update(changed=True, reboot_required=True)
        elif state == "domain" and _different(domain, current["dns_domain_name"]):
            if current["state"] == "domain":
                raise ValueError(
                    "Host is already joined to '{0}', switching domains is not implemented".format(
                        current["dns_domain_name"]
                    )
                )
            _online_join(
                parameters, requested_name if rename else None, result, check_mode
            )
            # The released upstream resets its diff hostname to the original
            # active name after a combined join/rename; preserve that interface.
            if rename:
                requested_name = current["hostname"]
                rename = False
        elif state == "workgroup" and _different(workgroup, current["workgroup_name"]):
            _workgroup_join(parameters, current, result, check_mode)
        if rename:
            if not check_mode:
                native.rename(
                    requested_name, user, password, domain_member=(state == "domain")
                )
            result.update(changed=True, reboot_required=True)
    except (OSError, ValueError) as error:
        result.update(failed=True, msg=str(error))
        return result
    if diff_mode:
        result["diff"]["after"] = {
            "dns_domain_name": domain,
            "hostname": requested_name,
            "state": state,
            "workgroup_name": workgroup,
        }
    return result


def _response():
    raw, parameters = {}, None
    result = {"changed": False, "reboot_required": False}
    try:
        raw = read_arguments(
            _PARAMETERS,
            "sustainablelobster.legacy_ad.membership",
            allow_unknown=True,
        )
        arguments = read_arguments(
            _PARAMETERS, "sustainablelobster.legacy_ad.membership"
        )
        parameters = _parameters(arguments)
        check = as_bool(
            arguments.get("_ansible_check_mode", False), "_ansible_check_mode"
        )
        diff = as_bool(arguments.get("_ansible_diff", False), "_ansible_diff")
        result = _manage(parameters, check, diff)
    # Each payload keeps its own secret-safe error envelope before emitting JSON.
    # pylint: disable=duplicate-code
    except (OSError, ValueError, UnicodeError) as error:
        result.update(failed=True, msg=str(error))
    # Unexpected boundary errors must also pass through credential redaction.
    except Exception as error:  # pylint: disable=broad-exception-caught
        result.update(
            failed=True,
            msg="Unhandled exception while executing module: " + str(error),
            exception=traceback.format_exc(),
        )
    return sanitize_result(result, raw, parameters)
    # pylint: enable=duplicate-code


def main():
    """Read a membership task and emit its native operation result.

    :raises SystemExit: After returning an Ansible JSON success or failure.
    """
    run_module(_response)


if __name__ == "__main__":
    main()
